test('booking create, overlap rejection, adjacent dates, edit, cancellation and history', async ({ page }) => {
  await createBuilding(page)
  await createRoom(page)
  await page.goto('/bookings')
  await bookingForm(page, 'QA Guest', '2027-03-01', '2027-03-10')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await bookingForm(page, 'QA Overlap', '2027-03-05', '2027-03-12')
  await expect(page.getByRole('alert')).toContainText('Lịch đặt bị trùng')
  await page.getByLabel('Ngày nhận phòng *').fill('2027-03-10')
  await page.getByLabel('Ngày trả phòng *').fill('2027-03-15')
  await page.getByRole('button', { name: 'Lưu thay đổi' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Sửa lịch của QA Guest', exact: true }).click()
  await expect(page.getByLabel('Ngày nhận phòng *')).toHaveValue('2027-03-01')
  await page.getByLabel('Tên khách hàng *').fill('QA Guest Edited')
  await page.getByRole('button', { name: 'Lưu thay đổi' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.reload()
  await expect(page.getByText('QA Guest Edited', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Hủy lịch của QA Guest Edited', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Hủy lịch đặt', exact: true }).click()
  const cancelledRow = page.locator('tbody tr').filter({ hasText: 'QA Guest Edited' })
  await expect(cancelledRow).toContainText('Đã hủy')
  await expect(cancelledRow.getByRole('button', { name: 'Sửa lịch của QA Guest Edited', exact: true })).toBeDisabled()
  await bookingForm(page, 'QA Replacement', '2027-03-01', '2027-03-10')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByLabel('Lọc theo trạng thái booking').selectOption('cancelled')
  await page.getByRole('searchbox').fill('QA Guest Edited')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.goto('/rooms')
  await page.getByRole('button', { name: 'Xóa phòng QA-101', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Xóa', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('kể cả booking đã hủy')
})

