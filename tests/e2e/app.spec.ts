import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { createBuilding, createRoom } from './helpers'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.waitForLoadState('networkidle')
})

async function bookingForm(page: Page, name: string, start: string, end: string) {
  await page.getByRole('button', { name: 'Thêm lịch đặt', exact: true }).click()
  await page.getByLabel('Phòng *', { exact: true }).selectOption({ label: 'QA Tower · Phòng QA-101' })
  await page.getByLabel('Tên khách hàng *').fill(name)
  await page.getByLabel('Số điện thoại *').fill('0912345678')
  await page.getByLabel('Ngày nhận phòng *').fill(start)
  await page.getByLabel('Ngày trả phòng *').fill(end)
  await page.getByRole('button', { name: 'Lưu thay đổi' }).click()
}

test('dashboard statistics, routes and initial seed persist after reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await expect(page.locator('.stat-value')).toHaveText(['3', '12', '7', '5'])
  const seed = await page.evaluate(() => localStorage.getItem('room-finder-estate-v1'))
  expect(seed).not.toBeNull()
  for (const [url, title] of [['/buildings', 'Tòa nhà'], ['/rooms', 'Phòng'], ['/bookings', 'Lịch đặt phòng']]) {
    await page.goto(url)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(title)
    await page.reload()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(title)
  }
  expect(await page.evaluate(() => localStorage.getItem('room-finder-estate-v1'))).toBe(seed)
  await page.goto('/unknown')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Trang này không tồn tại')
  expect(errors).toEqual([])
})

